// Inlines Leaflet into a TS module so the map WebView needs no CDN: map
// code never loads from a third party, only the tiles do.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const dist = dirname(require.resolve('leaflet/dist/leaflet.css'));
const js = readFileSync(join(dist, 'leaflet.js'), 'utf8');
const css = readFileSync(join(dist, 'leaflet.css'), 'utf8');
const out = join(dirname(fileURLToPath(import.meta.url)), '../src/map/leafletAssets.generated.ts');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// Generated by scripts/build-leaflet.mjs — do not edit.\nexport const LEAFLET_JS = ${JSON.stringify(js)};\nexport const LEAFLET_CSS = ${JSON.stringify(css)};\n`,
);
console.log('leaflet assets written');
